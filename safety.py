"""
Аварийное обесточивание стенда.

Отдельный модуль, потому что это единственный код, который обязан отработать
в любом состоянии программы: при нажатии «Стоп», при исключении в
измерительном цикле, при закрытии окна во время измерения. Он ничего не знает
про ход измерения и ни от чего не зависит, кроме переданных ему объектов
приборов.

Три правила, отличающие аварийный останов от штатного завершения:

1. **Порядок продиктован физикой, а не удобством.** Сначала гаснет выход
   источника, и только потом размыкается реле: размыкать реле под током —
   это дуга на контактах и приваренные контакты. Уставка тока/напряжения
   обнуляется уже после того, как выход погашен, — она влияет лишь на
   следующее включение.

2. **Ни один шаг не может помешать следующему.** Каждый в своём try/except:
   зависший мультиметр не должен стоить разомкнутого реле.

3. **Никаких ожиданий.** Ответ платы реле не вычитывается (штатный
   RelayController.off() ждёт 'OK' до полутора секунд), паузы не ставятся,
   повторов нет. VISA-таймаут приборов на время последовательности
   опускается до EMERGENCY_VISA_TIMEOUT_MS, иначе один неотвечающий прибор
   задержал бы размыкание реле на свои штатные 5 секунд.

Штатное завершение измерения этим модулем не пользуется: там уместны и
ожидание подтверждения от реле, и аккуратное закрытие сессий.
"""
from typing import Callable, List, Optional

# Насколько ужимается VISA-таймаут приборов на время аварийной
# последовательности. Ноль не годится: в VISA это «вернуть управление
# немедленно», из-за чего гарантированно провалились бы и те команды,
# которые прибор принял бы за десяток миллисекунд.
EMERGENCY_VISA_TIMEOUT_MS = 500


def _shorten_visa_timeout(instrument) -> None:
    """
    Ужимает таймаут VISA-сессии, чтобы неотвечающий прибор не растянул
    аварийную последовательность. Отсутствие атрибута (заглушка в тестах,
    уже закрытая сессия) — не ошибка.
    """
    try:
        instrument.instr.timeout = EMERGENCY_VISA_TIMEOUT_MS
    except Exception:
        pass


def emergency_shutdown(src=None, relay=None, dmm=None,
                        log: Optional[Callable[[str], None]] = None) -> List[str]:
    """
    Обесточивает стенд максимально быстро и возвращает список того, что
    реально удалось сделать, — в том же порядке, в каком выполнялось.

    Любой из аргументов может быть None: аварийный останов вызывается и до
    того, как все приборы успели открыться.

    Возвращаемый список нужен и для журнала оператора, и для тестов: он
    показывает, какие шаги прошли, а какие провалились, — в отличие от
    молчаливого «всё в try/except», по которому нельзя понять, разомкнулось
    ли реле на самом деле.
    """
    steps: List[str] = []

    def record(message: str) -> None:
        steps.append(message)
        if log is not None:
            log(f"[АВАРИЙНЫЙ ОСТАНОВ] {message}")

    for instrument in (src, dmm):
        if instrument is not None:
            _shorten_visa_timeout(instrument)

    # --- 1. Выход источника. Первым: реле нельзя размыкать под током. ---
    if src is not None:
        try:
            src.output_off()
            record("выход источника выключен")
        except Exception as e:
            record(f"НЕ УДАЛОСЬ выключить выход источника: {e}")

    # --- 2. Реле. Без ожидания ответа; не вышло — рвём порт. ---
    if relay is not None:
        try:
            relay.emergency_off()
            record("реле разомкнуто (команда отправлена без ожидания ответа)")
        except Exception as e:
            record(f"НЕ УДАЛОСЬ разомкнуть реле: {e}")
            # Порт мёртв или плата не отвечает. Обрыв порта — последнее, что
            # мы можем сделать программно: плата при потере связи уходит в
            # исходное состояние сама.
            try:
                relay.drop()
                record("порт реле принудительно закрыт")
            except Exception as e2:
                record(f"НЕ УДАЛОСЬ закрыть порт реле: {e2}")

    # --- 3. Уставки в ноль. Уже после того, как выход погашен. ---
    if src is not None:
        for method_name, arg in (('set_current', 0), ('set_voltage', 0)):
            method = getattr(src, method_name, None)
            if method is None:
                continue
            try:
                method(arg)
                record(f"{method_name}(0)")
            except Exception as e:
                record(f"НЕ УДАЛОСЬ {method_name}(0): {e}")

    # --- 4. Разрыв связи со всеми приборами. ---
    for name, instrument in (('источник', src), ('мультиметр', dmm), ('реле', relay)):
        if instrument is None:
            continue
        try:
            instrument.close()
            record(f"связь с прибором закрыта: {name}")
        except Exception as e:
            record(f"НЕ УДАЛОСЬ закрыть связь ({name}): {e}")

    return steps
